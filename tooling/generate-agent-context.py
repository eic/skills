#!/usr/bin/env python3
"""Render the agent context files under docs/agents.d/<site>/ from the site data model.

One YAML per site in tooling/agent-context/sites/ is deep-merged onto defaults.yaml,
so a site names only what differs. A null value means "not recorded": the templates then
tell the agent to find out instead of guessing.
"""
import argparse
import sys
from pathlib import Path

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined


ROOT = Path(__file__).resolve().parent.parent
MODEL = ROOT / "tooling" / "agent-context"
OUTPUT = ROOT / "docs" / "agents.d"
TOPICS = ["scope", "tools", "data", "site", "policies"]
UNRESOLVED_MARKER = "[NEEDS CLARIFICATION]"


def deep_merge(base, override):
    merged = dict(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = deep_merge(merged[key], value)
        else:
            merged[key] = value
    return merged


def load_site(site_file: Path) -> dict:
    defaults = yaml.safe_load((MODEL / "defaults.yaml").read_text(encoding="utf-8"))
    site = yaml.safe_load(site_file.read_text(encoding="utf-8"))
    return deep_merge(defaults, site)


def with_header(body: str, header: str) -> str:
    """The heading stays on line 1 (the docs check wants it there); the provenance comment follows."""
    heading, rest = body.split("\n", 1)
    return f"{heading}\n{header}{rest}\n"


def render_site(site: dict) -> dict:
    environment = Environment(
        loader=FileSystemLoader(MODEL / "templates"),
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
    )
    header = (
        f"<!-- Generated by tooling/generate-agent-context.py from "
        f"tooling/agent-context/sites/{site['site']}.yaml in eic/skills. Manual changes will be lost. -->\n"
    )
    bodies = {topic: environment.get_template(f"{topic}.md.j2").render(**site).strip() for topic in TOPICS}
    files = {f"{topic}.md": with_header(body, header) for topic, body in bodies.items()}
    assembled = "\n\n".join(f"<!-- Source: {topic}.md -->\n{bodies[topic]}" for topic in TOPICS)
    files["AGENTS.md"] = with_header(
        f"# {site['title']}: agent context\n\n"
        + "This file is the context for an assistant working on ePIC data through the EIC MCP\n"
        + "servers. Read it before acting.\n\n"
        + assembled,
        header,
    )
    for name, content in files.items():
        if UNRESOLVED_MARKER in content:
            raise SystemExit(f"{site['site']}/{name}: contains {UNRESOLVED_MARKER}")
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if docs/agents.d is out of date instead of writing")
    arguments = parser.parse_args()
    stale = []
    for site_file in sorted((MODEL / "sites").glob("*.yaml")):
        site = load_site(site_file)
        site_output = OUTPUT / site["site"]
        for name, content in render_site(site).items():
            target = site_output / name
            if arguments.check:
                if not target.exists() or target.read_text(encoding="utf-8") != content:
                    stale.append(target.relative_to(ROOT))
            else:
                site_output.mkdir(parents=True, exist_ok=True)
                target.write_text(content, encoding="utf-8")
                print(f"wrote {target.relative_to(ROOT)}")
    if stale:
        print("out of date (run tooling/generate-agent-context.py):", *stale, sep="\n  ", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
